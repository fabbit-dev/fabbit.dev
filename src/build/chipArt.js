// Artix-7 XC7A50T сверху, пиксельной иконкой в сетке 56×56 (как иконки бренд-кита, только крупнее).
// Корпус со скошенными углами, ключ первого вывода, маркировка и DataMatrix, как на настоящем чипе.
// Показывается только в целых масштабах: 4× на десктопе, 3× на телефоне.

export const CHIP_SIZE = 56;

// 5×7: заголовок
const BIG = {
  A: ['.###.', '#...#', '#...#', '#####', '#...#', '#...#', '#...#'],
  R: ['####.', '#...#', '#...#', '####.', '#.#..', '#..#.', '#...#'],
  T: ['#####', '..#..', '..#..', '..#..', '..#..', '..#..', '..#..'],
  I: ['#####', '..#..', '..#..', '..#..', '..#..', '..#..', '#####'],
  X: ['#...#', '#...#', '.#.#.', '..#..', '.#.#.', '#...#', '#...#'],
  '-': ['.....', '.....', '.....', '####.', '.....', '.....', '.....'],
  7: ['#####', '....#', '...#.', '..#..', '..#..', '..#..', '..#..'],
};
// 3×5: номер кристалла
const SMALL = {
  X: ['#.#', '#.#', '.#.', '#.#', '#.#'],
  C: ['###', '#..', '#..', '#..', '###'],
  7: ['###', '..#', '.#.', '.#.', '.#.'],
  A: ['.#.', '#.#', '###', '#.#', '#.#'],
  5: ['###', '#..', '###', '..#', '###'],
  0: ['###', '#.#', '#.#', '#.#', '###'],
  T: ['###', '.#.', '.#.', '.#.', '.#.'],
};

function chipGrid() {
  const N = CHIP_SIZE;
  const G = Array.from({ length: N }, () => new Array(N).fill(false));
  const set = (x, y) => { if (x >= 0 && y >= 0 && x < N && y < N) G[y][x] = true; };
  const rect = (x, y, w, h) => { for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) set(x + i, y + j); };
  const text = (font, s, x, y) => {
    for (const ch of s) {
      const g = font[ch];
      g.forEach((row, r) => [...row].forEach((c, k) => c === '#' && set(x + k, y + r)));
      x += g[0].length + 1;
    }
  };

  // корпус: рамка 1 клетка, углы скошены на 2
  const a = 2, b = N - 3;
  for (let i = a + 2; i <= b - 2; i++) { set(i, a); set(i, b); set(a, i); set(b, i); }
  set(a + 1, a + 1); set(b - 1, a + 1); set(a + 1, b - 1); set(b - 1, b - 1);
  // ключ первого вывода
  rect(7, 7, 3, 3);
  // маркировка
  text(BIG, 'ARTIX-7', 7, 14);
  text(SMALL, 'XC7A50T', 7, 25);
  // DataMatrix 14×14: сплошные левый и нижний края, пунктир сверху и справа, внутри шум
  const dx = 36, dy = 34, D = 14;
  for (let i = 0; i < D; i++) {
    set(dx, dy + i); set(dx + i, dy + D - 1);
    if (i % 2 === 0) { set(dx + i, dy); set(dx + D - 1, dy + D - 1 - i); }
  }
  for (let j = 1; j < D - 1; j++) for (let i = 1; i < D - 1; i++) if (((i * 7 + j * 13 + i * j) % 5) < 2) set(dx + i, dy + j);
  // черта под маркировкой
  rect(7, 44, 24, 1);
  return G;
}

// Путь SVG: по прямоугольнику на каждый горизонтальный отрезок
export const CHIP_PATH = chipGrid().map((row, y) => {
  let d = '';
  for (let x = 0; x < row.length;) {
    if (!row[x]) { x++; continue; }
    const x0 = x; while (x < row.length && row[x]) x++;
    d += `M${x0} ${y}h${x - x0}v1h-${x - x0}z`;
  }
  return d;
}).join('');
